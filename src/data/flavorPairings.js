const ACCENTS_REGEX = /[̀-ͯ]/g

function normalize(str) {
  return str.trim().toLowerCase().normalize('NFD').replace(ACCENTS_REGEX, '')
}

/**
 * Renvoie tous les mariages de saveurs dont TOUS les ingrédients-clés sont
 * présents dans `availableIngredients` (correspondance normalisée, tolérante
 * aux accents/casse). Un mariage à 3 ingrédients ne "matche" que si les 3
 * sont là — pas de correspondance partielle, pour ne jamais proposer une
 * recette à laquelle il manquerait sa pièce maîtresse.
 * @param {string[]} availableIngredients
 * @returns {object[]}
 */
export function findFlavorPairings(availableIngredients) {
  if (!availableIngredients || availableIngredients.length === 0) return []
  const availableNorm = availableIngredients.map(normalize)
  return FLAVOR_PAIRINGS.filter((pairing) =>
    pairing.ingredients.every((ing) => availableNorm.includes(normalize(ing)))
  )
}
