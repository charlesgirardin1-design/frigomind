// Traduit un nom d'ingrédient canonique pour l'affichage uniquement — ne
// touche jamais à la valeur sous-jacente utilisée pour le matching, les
// quantités ou la navigation. Insensible à la casse pour rester robuste
// face à une variante mal cassée ; retombe sur le nom français si absent
// de la table plutôt que d'afficher un vide.
export function translateIngredientName(name, lang) {
  if (lang !== 'en' || !name) return name
  return INGREDIENT_TRANSLATIONS_EN[name] || INGREDIENT_TRANSLATIONS_EN[name.toLowerCase()] || name
}
